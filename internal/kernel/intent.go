package kernel

import "strings"

// harnessEnvelopes are the tags a coding client wraps around text it adds to a
// user turn on its own: environment notes, the file open in the editor, the
// editor selection, a subagent's or another session's report, a background
// task notice, the output of a local command. They are context, not a request
// from the user. A tag may carry attributes (<agent-message from="...">).
var harnessEnvelopes = []string{
	"system-reminder", "ide_opened_file", "ide_selection",
	"agent-message", "task-notification", "local-command-stdout", "local-command-stderr",
	"local-command-caveat",
}

// harnessLines are whole lines a client sends as a user turn on its own, or
// puts before the text it relays.
var harnessLines = map[string]bool{
	"Tool loaded.":                                        true,
	"Another Claude session sent a message:":              true,
	"The user sent a new message while you were working:": true,
	"[Request interrupted by user]":                       true,
	"[Request interrupted by user for tool use]":          true,
}

// harnessNotePrefixes start a line of guidance the client appends to a relayed
// message (a subagent report, a message sent mid-turn). The line is dropped.
var harnessNotePrefixes = []string{
	`That "other Claude session" is an agent working inside this same session`,
	"This is how Claude Code surfaces messages the user sends mid-turn",
}

// harnessPrefixes start a user turn that the client writes entirely on its
// own: the summary that continues a compacted conversation, the request to
// resume a cut-off answer. Such a turn opens no intent.
var harnessPrefixes = []string{
	"This session is being continued from a previous conversation",
	"Your response above was cut off mid-stream.",
	"Caveat: The messages below were generated by the user while running local commands.",
}

// acknowledgements are replies that confirm or answer something already in
// progress ("mergeado", "sim", "ok"). They carry no new request, so they open
// no intent; the intent they answer stays open. Compared in lower case with
// trailing punctuation removed.
var acknowledgements = map[string]bool{
	"sim": true, "s": true, "ok": true, "okay": true, "certo": true, "beleza": true, "blz": true,
	"feito": true, "pronto": true, "mergeado": true, "mergeei": true, "merged": true,
	"done": true, "yes": true, "y": true, "obrigado": true, "valeu": true, "thanks": true,
	"continue": true, "continua": true, "prossiga": true, "pode seguir": true, "go on": true,
}

// IntentText is the relevant excerpt of a user message for its intent (spec
// §11.3: "o texto literal (ou o trecho relevante)"). It drops the harness
// envelopes and lines above and trims the rest. An empty result means the
// message carries no request from the user, so it opens no intent.
// An unclosed envelope is kept as text.
func IntentText(text string) string {
	for _, tag := range harnessEnvelopes {
		text = stripTag(text, tag)
	}
	lines := strings.Split(text, "\n")
	kept := lines[:0]
	for _, l := range lines {
		if t := strings.TrimSpace(l); !harnessLines[t] && !hasAnyPrefix(t, harnessNotePrefixes) {
			kept = append(kept, l)
		}
	}
	out := strings.TrimSpace(strings.Join(kept, "\n"))
	if hasAnyPrefix(out, harnessPrefixes) {
		return ""
	}
	if acknowledgements[strings.TrimRight(strings.ToLower(out), ".!?, ")] {
		return ""
	}
	return out
}

// IntentPreview is IntentText cut to the length the <intents> block shows for
// an open intent.
func IntentPreview(text string) string {
	return clip(IntentText(text), maxOpenIntentRunes)
}

// stripTag removes every <tag ...>...</tag> span from s. The open tag is
// "<tag>" or "<tag" followed by white space and attributes.
func stripTag(s, tag string) string {
	open, close := "<"+tag, "</"+tag+">"
	var b strings.Builder
	for {
		i := openTag(s, open)
		if i < 0 {
			break
		}
		gt := strings.IndexByte(s[i:], '>')
		if gt < 0 {
			break
		}
		body := i + gt + 1
		j := strings.Index(s[body:], close)
		if j < 0 {
			break
		}
		b.WriteString(s[:i])
		s = s[body+j+len(close):]
	}
	if b.Len() == 0 {
		return s
	}
	b.WriteString(s)
	return b.String()
}

// openTag returns the index of the first open (as "<tag") in s that is followed
// by '>' or white space, so "<agent-message" does not match "<agent-messages".
func openTag(s, open string) int {
	off := 0
	for {
		i := strings.Index(s[off:], open)
		if i < 0 {
			return -1
		}
		i += off
		if k := i + len(open); k < len(s) && strings.IndexByte("> \t\n\r", s[k]) >= 0 {
			return i
		}
		off = i + len(open)
	}
}

// hasAnyPrefix reports whether s starts with one of prefixes.
func hasAnyPrefix(s string, prefixes []string) bool {
	for _, p := range prefixes {
		if strings.HasPrefix(s, p) {
			return true
		}
	}
	return false
}
