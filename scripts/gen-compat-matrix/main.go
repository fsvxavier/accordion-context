// Command gen-compat-matrix prints docs/compatibility.md: the clients, protocols,
// integration modes and status that the binary supports (spec section 19.9,
// "Matriz de compatibilidade publicada").
//
// Usage:
//
//	go run ./scripts/gen-compat-matrix > docs/compatibility.md
//
// Clients come from launcher.BuiltinProfiles. Protocols come from the codec
// packages under internal/wire; their symbols are referenced in protocols. A profile without a
// protocol entry in clientProtocols makes the generator fail, which keeps the
// matrix honest when a client is added.
package main

import (
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/fsvxavier/accordion-context/internal/launcher"
	"github.com/fsvxavier/accordion-context/internal/wire/anthropic"
	"github.com/fsvxavier/accordion-context/internal/wire/google"
	"github.com/fsvxavier/accordion-context/internal/wire/openai"
	"github.com/fsvxavier/accordion-context/internal/wire/responses"
)

type protocol struct {
	name     string
	endpoint string
	// refs keeps the codec symbols the matrix describes. The references make the
	// generator stop compiling when a codec loses one of them.
	refs []any
	// features are the capabilities the codec provides, as the matrix names them.
	features []string
}

// protocols lists the codecs.
var protocols = []protocol{
	{
		name: "anthropic", endpoint: "POST /v1/messages",
		refs: []any{anthropic.Decode, anthropic.Encode, anthropic.ParseCompressArgs,
			anthropic.StreamPassthrough, anthropic.InjectTools, anthropic.ParseUsage},
		features: allFeatures,
	},
	{
		name: "openai", endpoint: "POST /v1/chat/completions",
		refs: []any{openai.Decode, openai.Encode, openai.ParseCompressArgs,
			openai.StreamPassthrough, openai.InjectTools, openai.ParseUsage},
		features: allFeatures,
	},
	{
		name: "responses", endpoint: "POST /v1/responses",
		refs: []any{responses.Decode, responses.Encode, responses.ParseCompressArgs,
			responses.StreamPassthrough, responses.InjectTools, responses.ParseUsage},
		features: allFeatures,
	},
	{
		name: "google", endpoint: "POST models/*:generateContent, :streamGenerateContent",
		refs: []any{google.Decode, google.Encode, google.ParseCompressArgs,
			google.StreamPassthrough, google.InjectTools, google.ParseUsage},
		features: allFeatures,
	},
}

var allFeatures = []string{"request codec", "compress args", "stream passthrough", "tool injection", "usage"}

// clientProtocols maps a built-in profile to the protocols its base URL can
// send. A profile without an entry is an error.
var clientProtocols = map[string][]string{
	"claude":          {"anthropic"},
	"codex":           {"openai", "responses"},
	"gemini":          {"google"},
	"opencode":        {"anthropic"},
	"opencode-openai": {"openai", "responses"},
}

func main() {
	if err := generate(os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "gen-compat-matrix:", err)
		os.Exit(1)
	}
}

func generate(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Compatibility matrix\n\n")
	b.WriteString("<!-- Generated by `go run ./scripts/gen-compat-matrix`. Do not edit by hand. -->\n\n")
	b.WriteString("Spec section 19.9. Protocols are the wire codecs under `internal/wire`; clients are the built-in launcher profiles in `internal/launcher`.\n\n")

	b.WriteString("## Protocols\n\n")
	b.WriteString("| Protocol | Endpoint | Features |\n")
	b.WriteString("|---|---|---|\n")
	byName := map[string]protocol{}
	for _, p := range protocols {
		byName[p.name] = p
		b.WriteString(fmt.Sprintf("| %s | %s | %s |\n", p.name, p.endpoint, strings.Join(p.features, ", ")))
	}

	b.WriteString("\n## Clients\n\n")
	b.WriteString("| Client | Command | Upstream | Protocols | Mode | Base URL variable | Status |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, p := range launcher.BuiltinProfiles() {
		names, ok := clientProtocols[p.Name]
		if !ok {
			return fmt.Errorf("client %q has no entry in clientProtocols", p.Name)
		}
		for _, n := range names {
			if _, ok := byName[n]; !ok {
				return fmt.Errorf("client %q names unknown protocol %q", p.Name, n)
			}
		}
		cmd := strings.Join(p.Match, ", ")
		if len(names) == 0 {
			names = []string{"none"}
		}
		mode, status := "MITM (spec 19.9, degree 5)", "not launched: no base URL variable, flag or temp config"
		variable := "-"
		switch {
		case p.BaseURLEnv != "":
			mode, status = "base URL (spec 19.9, degree 3)", "supported"
			variable = "`" + p.BaseURLEnv + "`"
		case p.TempConfig != nil:
			mode, status = "temp config (spec 19.9, degree 4)", "supported"
			variable = "`" + p.TempConfig.PathEnv + "` (temp file)"
		}
		b.WriteString(fmt.Sprintf("| %s | %s | %s | %s | %s | %s | %s |\n",
			p.Name, cmd, p.Upstream, strings.Join(names, ", "), mode, variable, status))
	}

	b.WriteString("\n## Status legend\n\n")
	b.WriteString("- **supported**: the launcher points the client at the proxy, through the base URL variable or a temp config file, and the protocols above handle the requests.\n")
	b.WriteString("- **not launched**: the client has no base URL variable, flag or temp config, so the launcher refuses it (`launcher.ErrNoBaseURL`).\n")
	_, err := io.WriteString(w, b.String())
	return err
}
